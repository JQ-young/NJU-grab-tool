# ---------------- 位串工具 ----------------

def _bt4_to_hex(b4):
    return {
        "0000": "0", "0001": "1", "0010": "2", "0011": "3",
        "0100": "4", "0101": "5", "0110": "6", "0111": "7",
        "1000": "8", "1001": "9", "1010": "A", "1011": "B",
        "1100": "C", "1101": "D", "1110": "E", "1111": "F",
    }[b4]


def _bt64_to_hex(r):
    out = ""
    for i in range(16):
        s = ""
        for j in range(4):
            s += str(r[4 * i + j])
        out += _bt4_to_hex(s)
    return out


def str_to_bt(s):
    """字符串 → 64位数组（每字符16位MSB在前，不足4字符补零位）"""
    a = [0] * 64
    n = len(s)
    for i in range(min(n, 4)):
        c = ord(s[i])
        for t in range(16):
            a[16 * i + t] = (c // (1 << (15 - t))) % 2
    return a


# ---------------- DES 核心 ----------------

def _init_permute(r):
    e = [0] * 64
    for i in range(4):
        for j in range(8):
            m, n = 2 * i + 1, 2 * i
            e[8 * i + j] = r[8 * (7 - j) + m]
            e[8 * i + j + 32] = r[8 * (7 - j) + n]
    return e


def _expand_permute(r):
    e = [0] * 48
    for i in range(8):
        e[6 * i + 0] = r[31] if i == 0 else r[4 * i - 1]
        e[6 * i + 1] = r[4 * i + 0]
        e[6 * i + 2] = r[4 * i + 1]
        e[6 * i + 3] = r[4 * i + 2]
        e[6 * i + 4] = r[4 * i + 3]
        e[6 * i + 5] = r[0] if i == 7 else r[4 * i + 4]
    return e


def _xor(r, e):
    return [r[i] ^ e[i] for i in range(len(r))]


