def get_key_bytes(key):
    """密钥字符串 → 若干64位数组（每4字符一块，末块不足补零）"""
    a = []
    n, t = divmod(len(key), 4)
    for s in range(n):
        a.append(str_to_bt(key[4 * s: 4 * s + 4]))
    if t > 0:
        a.append(str_to_bt(key[4 * n:]))
    return a


def str_enc(data, first_key=None, second_key=None, third_key=None):
    """与 DES.js strEnc 完全一致：按4字符分块，逐块依次用所有密钥块加密，输出十六进制串"""
    keys_bt = []
    for k in (first_key, second_key, third_key):
        if k:
            keys_bt.extend(get_key_bytes(k))
    i = len(data)
    u = ""
    k = i // 4
    y = i % 4
    for v in range(k):
        w = str_to_bt(data[4 * v: 4 * v + 4])
        for kb in keys_bt:
            w = enc(w, kb)
        u += _bt64_to_hex(w)
    if y > 0:
        w = str_to_bt(data[4 * k:])
        for kb in keys_bt:
            w = enc(w, kb)
        u += _bt64_to_hex(w)
    return u
