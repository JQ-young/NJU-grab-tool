def enc(r, key_bt64):
    a = _generate_keys(key_bt64)
    n = _init_permute(r)
    t, s = n[:32], n[32:]
    for c in range(16):
        o = t[:]
        t = s[:]
        l = a[c]
        b = _xor(_p_permute(_s_box_permute(_xor(_expand_permute(s), l))), o)
        s = b
    k = s + t
    return _finally_permute(k)


