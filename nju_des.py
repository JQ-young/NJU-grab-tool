    for m in range(8):
        l = 2 * r[6 * m + 0] + r[6 * m + 5]
        b = 2 * r[6 * m + 1] * 2 * 2 + 2 * r[6 * m + 2] * 2 + 2 * r[6 * m + 3] + r[6 * m + 4]
